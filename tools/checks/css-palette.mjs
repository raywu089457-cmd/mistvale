// css-palette.mjs — 把 src/pixel-style.css 的色碼依 ΔE76 ≤ 2(肉眼分不出)分群,用 ≥3 次的群組成色彩 token 表(實驗 5 第 0 階段)。
// 用法:node tools/checks/css-palette.mjs [--write docs/research/ui-palette.json] [--check docs/research/ui-palette.json]
//   --write:產生表(token 名先是 --c-01…,由命名卡改成語意名);每群:代表色(用最多次的那個)、成員、次數、前 4 個選擇器、A/B 半各幾次。
//   --check:驗表:每個 token 名是 kebab-case、不重複、不是 --c-NN 佔位名、成員沒有被改動。
//   只處理 3/6 位數色碼;帶透明度的 4/8 位數不併(合併會改透明度)。
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const args = process.argv.slice(2);
const opt = k => { const i = args.indexOf('--' + k); return i >= 0 ? args[i + 1] : null; };
const css = fs.readFileSync(path.join(ROOT, 'src/pixel-style.css'), 'utf8');
const cut = css.indexOf('/* @split color');
const norm = h => { h = h.toLowerCase().slice(1); return '#' + (h.length === 3 ? [...h].map(c => c + c).join('') : h); };
const lab = h => { const [r, g, b] = [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16)); const f = c => { c /= 255; return c > .04045 ? ((c + .055) / 1.055) ** 2.4 : c / 12.92; };
  const [R, G, B] = [f(r), f(g), f(b)], t = v => v > .008856 ? Math.cbrt(v) : 7.787 * v + 16 / 116;
  const x = t((R * .4124 + G * .3576 + B * .1805) / .95047), y = t(R * .2126 + G * .7152 + B * .0722), z = t((R * .0193 + G * .1192 + B * .9505) / 1.08883);
  return [116 * y - 16, 500 * (x - y), 200 * (y - z)]; };
const dE = (a, b) => Math.hypot(...a.map((v, i) => v - b[i]));

// every use: colour, half, selector (text before the nearest preceding '{' that is not a @media)
const uses = [];
const rootEnd = css.search(/^\s*:root\s*\{/m) >= 0 ? css.indexOf('}', css.search(/^\s*:root\s*\{/m)) : -1;
for (const m of css.matchAll(/#(?:[0-9a-f]{6}|[0-9a-f]{3})\b(?![0-9a-f])/gi)) {
  if (m.index < rootEnd && m.index > css.search(/^\s*:root\s*\{/m)) continue;
  const open = css.lastIndexOf('{', m.index), prev = Math.max(css.lastIndexOf('}', open), css.lastIndexOf('{', open - 1));
  uses.push({ hex: norm(m[0]), half: m.index < cut ? 'A' : 'B', sel: css.slice(prev + 1, open).replace(/\/\*[\s\S]*?\*\//g, '').trim().slice(0, 60) });
}
const count = {}; for (const u of uses) count[u.hex] = (count[u.hex] || 0) + 1;

if (opt('write')) {
  const groups = [];
  for (const hex of Object.keys(count).sort((a, b) => count[b] - count[a])) {   // most-used first, so it becomes the representative
    const l = lab(hex), g = groups.find(g => dE(g.l, l) <= 2 && g.members.every(m => dE(lab(m), l) <= 2));
    g ? g.members.push(hex) : groups.push({ l, members: [hex] });
  }
  const tokens = groups.map(g => ({ ...g, n: g.members.reduce((s, h) => s + count[h], 0) })).filter(g => g.n >= 3).map((g, i) => {
    const u = uses.filter(x => g.members.includes(x.hex));
    return { name: `--c-${String(i + 1).padStart(2, '0')}`, value: g.members[0], members: g.members, uses: g.n,
      A: u.filter(x => x.half === 'A').length, B: u.filter(x => x.half === 'B').length, selectors: [...new Set(u.map(x => x.sel))].slice(0, 4) };
  });
  const out = { note: 'Generated by tools/checks/css-palette.mjs. Rename `name` only; do not edit value/members.', deltaE: 2, minUses: 3,
    totals: { tokens: tokens.length, uses: tokens.reduce((s, t) => s + t.uses, 0), A: tokens.reduce((s, t) => s + t.A, 0), B: tokens.reduce((s, t) => s + t.B, 0) }, tokens };
  fs.mkdirSync(path.dirname(path.join(ROOT, opt('write'))), { recursive: true });
  fs.writeFileSync(path.join(ROOT, opt('write')), JSON.stringify(out, null, 1));
  console.log(`css-palette: ${tokens.length} tokens cover ${out.totals.uses} uses (A ${out.totals.A}, B ${out.totals.B}) → ${opt('write')}`);
}
if (opt('check')) {
  const t = JSON.parse(fs.readFileSync(path.join(ROOT, opt('check')), 'utf8')).tokens, bad = [];
  const names = t.map(x => x.name);
  for (const x of t) {
    if (!/^--[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(x.name)) bad.push(`not kebab-case: ${x.name}`);
    if (/^--c-\d+$/.test(x.name)) bad.push(`placeholder name left: ${x.name}`);
    if (x.members[0] !== x.value || x.members.some(h => !count[h])) bad.push(`value/members edited: ${x.name}`);
  }
  for (const n of new Set(names)) if (names.filter(m => m === n).length > 1) bad.push(`duplicate name: ${n}`);
  // any custom property defined anywhere in the file (there are several :root blocks); a definition with the token's own value is the token itself
  const defs = [...css.matchAll(/(--[\w-]+)\s*:\s*([^;}]+)/g)].map(m => [m[1], m[2].trim().toLowerCase()]);
  for (const x of t) if (defs.some(([n, v]) => n === x.name && v !== x.value)) bad.push(`clashes with an existing custom property: ${x.name}`);
  console.log(`css-palette check: ${t.length} tokens, ${bad.length} problems`); for (const b of bad.slice(0, 20)) console.log('  ' + b);
  process.exit(bad.length ? 1 : 0);
}
