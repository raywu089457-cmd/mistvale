class FakeCanvas {
  constructor(w, h) {
    this.width = w;
    this.height = h;
    this.data = new Uint8ClampedArray(Math.max(0, w * h * 4));
    this._ctx = null;
  }
  getContext() {
    if (!this._ctx) this._ctx = new FakeCtx(this);
    return this._ctx;
  }
}

function pixelsOf(img) {
  if (!img) throw new Error('fake canvas: no image');
  if (img instanceof FakeCanvas) return img.data;
  if (img.data instanceof Uint8ClampedArray) return img.data;
  throw new Error('fake canvas: unsupported image source');
}

class FakeCtx {
  constructor(cv) {
    this.cv = cv;
    this.m = { a: 1, b: 0, c: 0, d: 1, e: 0, f: 0 };
    this.stack = [];
    this.imageSmoothingEnabled = false;
    this.fillStyle = '#000';
    this.font = '';
  }
  save() { this.stack.push({ ...this.m }); }
  restore() { if (this.stack.length) this.m = this.stack.pop(); }
  setTransform(a, b, c, d, e, f) { this.m = { a, b, c, d, e, f }; }
  translate(x, y) {
    const m = this.m;
    this.m = { a: m.a, b: m.b, c: m.c, d: m.d, e: m.e + m.a * x + m.c * y, f: m.f + m.b * x + m.d * y };
  }
  scale(x, y) {
    const m = this.m;
    this.m = { a: m.a * x, b: m.b * x, c: m.c * y, d: m.d * y, e: m.e, f: m.f };
  }
  clearRect(x, y, w, h) {
    for (let yy = y; yy < y + h; yy++) for (let xx = x; xx < x + w; xx++) {
      if (xx < 0 || yy < 0 || xx >= this.cv.width || yy >= this.cv.height) continue;
      this.cv.data.fill(0, (yy * this.cv.width + xx) * 4, (yy * this.cv.width + xx) * 4 + 4);
    }
  }
  drawImage(img, ...args) {
    const src = pixelsOf(img);
    const sw0 = img.width;
    const sh0 = img.height;
    let sx, sy, sw, sh, dx, dy, dw, dh;
    if (args.length === 2) { sx = 0; sy = 0; sw = sw0; sh = sh0; dx = args[0]; dy = args[1]; dw = sw; dh = sh; }
    else if (args.length === 4) { sx = 0; sy = 0; sw = sw0; sh = sh0; dx = args[0]; dy = args[1]; dw = args[2]; dh = args[3]; }
    else { [sx, sy, sw, sh, dx, dy, dw, dh] = args; }
    const m = this.m;
    const outW = this.cv.width;
    const outH = this.cv.height;
    const dst = this.cv.data;
    for (let y = 0; y < sh; y++) {
      const srcY = Math.floor(sy + y);
      if (srcY < 0 || srcY >= sh0) continue;
      const cy = (y + 0.5) * (dh / sh) + dy;
      for (let x = 0; x < sw; x++) {
        const srcX = Math.floor(sx + x);
        if (srcX < 0 || srcX >= sw0) continue;
        const cx = (x + 0.5) * (dw / sw) + dx;
        const ox = Math.floor(m.a * cx + m.c * cy + m.e);
        const oy = Math.floor(m.b * cx + m.d * cy + m.f);
        if (ox < 0 || oy < 0 || ox >= outW || oy >= outH) continue;
        const si = (srcY * sw0 + srcX) * 4;
        const di = (oy * outW + ox) * 4;
        const sa = src[si + 3];
        if (!sa) continue;
        const da = dst[di + 3];
        if (!da) {
          dst[di] = src[si]; dst[di + 1] = src[si + 1]; dst[di + 2] = src[si + 2]; dst[di + 3] = sa;
        } else {
          const k = sa / 255;
          const dk = da / 255;
          const oa = k + dk * (1 - k);
          dst[di] = Math.round((src[si] * k + dst[di] * dk * (1 - k)) / oa);
          dst[di + 1] = Math.round((src[si + 1] * k + dst[di + 1] * dk * (1 - k)) / oa);
          dst[di + 2] = Math.round((src[si + 2] * k + dst[di + 2] * dk * (1 - k)) / oa);
          dst[di + 3] = Math.round(oa * 255);
        }
      }
    }
  }
  getImageData(sx, sy, w, h) {
    const out = new Uint8ClampedArray(w * h * 4);
    const cw = this.cv.width;
    const ch = this.cv.height;
    for (let y = 0; y < h; y++) {
      const yy = sy + y;
      if (yy < 0 || yy >= ch) continue;
      const x0 = Math.max(0, sx);
      const x1 = Math.min(cw, sx + w);
      if (x1 <= x0) continue;
      out.set(this.cv.data.subarray((yy * cw + x0) * 4, (yy * cw + x1) * 4), (y * w + (x0 - sx)) * 4);
    }
    return { data: out, width: w, height: h };
  }
  putImageData(data, dx, dy) {
    const cw = this.cv.width;
    for (let y = 0; y < data.height; y++) for (let x = 0; x < data.width; x++) {
      const ox = dx + x;
      const oy = dy + y;
      if (ox < 0 || oy < 0 || ox >= cw || oy >= this.cv.height) continue;
      const si = (y * data.width + x) * 4;
      const di = (oy * cw + ox) * 4;
      this.cv.data[di] = data.data[si];
      this.cv.data[di + 1] = data.data[si + 1];
      this.cv.data[di + 2] = data.data[si + 2];
      this.cv.data[di + 3] = data.data[si + 3];
    }
  }
}

