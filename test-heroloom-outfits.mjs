/** Minimal character.json: one part per class-look id, opaque ink in every cell. */
function makeProviderSpec() {
  const layers = {
    back: ['main'], cape: ['main'], hair: ['main', 'back', 'under'], hat: ['main', 'back'],
    body: ['main', 'back', 'front', 'head'], top: ['main', 'back', 'front'], shield: ['main'],
    bottom: ['main'], shoes: ['main'], weapon: ['main', 'back'], face: ['main'], acc: ['main'],
  };
  const partsFor = {
    back: ['backpack'], cape: ['cape'], hair: ['short', 'spiky', 'ponytail', 'long'],
    hat: ['wizard', 'helmet', 'band'], body: ['base'], top: ['tunic', 'robe', 'armor'],
    shield: ['buckler'], bottom: ['pants', 'skirt'], shoes: ['boots', 'sandals'],
    weapon: ['sword', 'staff', 'dagger', 'bow'], face: ['eyes'], acc: ['glasses', 'beard'],
  };
  const slots = {};
  for (const [slot, layerIds] of Object.entries(layers)) {
    const parts = {};
    for (const id of partsFor[slot]) {
      const rels = {};
      for (const layer of layerIds) rels[layer] = `parts/${slot}-${id}-${layer}.png`;
      parts[id] = { layers: rels };
    }
    slots[slot] = { parts, ...(slot === 'body' || slot === 'face' ? { required: true } : {}) };
  }
  return { cell: [64, 56], columns: 8, foot: [26, 51], slots };
}

/**
 * Install fake XHR + Image globals. `assets(url)` decides what a URL yields:
 * {ok:true, image} or {ok:false}. Every image request goes through the mocked Image src setter,
 * so opts.trackImage sees exactly the pack preload calls (the outfit path passes track undefined).
 */
function installBrowserFakes(spec, assets) {
  const tracked = [];
  const requested = [];
  class FakeXHR {
    constructor() { this.status = 0; this.responseText = ''; this.onload = null; this.onerror = null; }
    open(method, url) { this._url = url; }
    send() {
      setTimeout(() => {
        if (String(this._url).endsWith('character.json')) {
          this.status = 200;
          this.responseText = JSON.stringify(spec);
          if (this.onload) this.onload();
        } else {
          this.status = 404;
          if (this.onload) this.onload();
        }
      }, 0);
    }
  }
  class FakeImage {
    constructor() { this._src = ''; this.onload = null; this.onerror = null; this.width = 0; this.height = 0; }
    get src() { return this._src; }
    set src(v) {
      this._src = v;
      requested.push(v);
      setTimeout(() => {
        const res = assets(v);
        if (res && res.ok) {
          const img = res.image;
          this.width = img.width;
          this.height = img.height;
          this.naturalWidth = img.naturalWidth;
          this.naturalHeight = img.naturalHeight;
          this.data = img.data;
          if (this.onload) this.onload();
        } else if (this.onerror) {
          this.onerror(new Error('mock image error ' + v));
        }
      }, 0);
    }
  }
  const prev = { XMLHttpRequest: globalThis.XMLHttpRequest, Image: globalThis.Image };
  globalThis.XMLHttpRequest = FakeXHR;
  globalThis.Image = FakeImage;
  return {
    tracked,
    requested,
    restore() {
      if (prev.XMLHttpRequest === undefined) delete globalThis.XMLHttpRequest; else globalThis.XMLHttpRequest = prev.XMLHttpRequest;
      if (prev.Image === undefined) delete globalThis.Image; else globalThis.Image = prev.Image;
    },
  };
}

