function fillSheetCells(width, height, opts = {}) {
  const data = new Uint8ClampedArray(width * height * 4);
  const skip = opts.skip || (() => false);
  const alpha = opts.alpha == null ? 255 : opts.alpha;
  for (let row = 0; row < 8; row++) {
    for (let col = 0; col < 8; col++) {
      if (skip(row, col)) continue;
      const x0 = col * CELL_W + 20;
      const y0 = row * CELL_H + 20;
      for (let y = y0; y < y0 + 24; y++) {
        for (let x = x0; x < x0 + 24; x++) {
          const o = (y * width + x) * 4;
          data[o] = 200; data[o + 1] = 120; data[o + 2] = 80; data[o + 3] = alpha;
        }
      }
    }
  }
  return data;
}

