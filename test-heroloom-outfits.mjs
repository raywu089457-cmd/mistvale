function realSheetFiles() {
  const found = [];
  const walk = (dir) => {
    if (!fs.existsSync(dir)) return;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(p);
      else if (/\.png$/i.test(entry.name)) found.push(p);
    }
  };
  walk(path.join(root, 'assets', 'heroloom-outfits'));
  walk(path.join(root, 'media', 'heroloom-outfits'));
  walk(path.join(root, 'output', 'heroloom-ext', 'archer'));
  return found;
}

test('report: on-disk outfit sheets (skip when the art has not been delivered yet)', () => {
  const files = realSheetFiles();
  if (!files.length) {
    console.log('report: no outfit sheets on disk yet (media/heroloom-outfits/ and output/heroloom-ext/archer/ are empty)');
    return;
  }
  console.log(`report: ${files.length} outfit sheet candidate(s) on disk`);
  for (const file of files) {
    const rel = path.relative(root, file);
    let buf;
    try { buf = fs.readFileSync(file); } catch (e) { console.log(`  ${rel}: read failed (${e.message})`); continue; }
    const v = validateOutfitSheet(buf);
    if (!v.ok) {
      console.log(`  ${rel}: invalid — ${v.errors.join('; ')}`);
      continue;
    }
    let decoded;
    try { decoded = decodePng(buf); } catch (e) { console.log(`  ${rel}: valid header, decode skipped (${e.message})`); continue; }
    const scan = outfitSheetFrames(decoded.data, decoded.width, decoded.height);
    const used = scan.rows.map((r) => `${r.action} ${r.used}/${r.frames}`).join(' · ');
    console.log(`  ${rel}: ${decoded.width}x${decoded.height} ok=${scan.ok} ${used}`);
    if (!scan.ok) {
      for (const row of scan.rows) {
        if (row.empty.length) console.log(`    unusable ${row.action}: cells ${row.empty.join(',')}`);
      }
    }
  }
});

