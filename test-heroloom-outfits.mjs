const PNG_SIG = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c >>> 0;
  }
  return table;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function pngChunk(type, data) {
  const t = Buffer.from(type, 'latin1');
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([t, data])), 0);
  return Buffer.concat([len, t, data, crc]);
}

/** Build a valid non-interlaced PNG (filter 0 rows) from RGBA data. */
function makePng(width, height, rgba, opts = {}) {
  const bitDepth = opts.bitDepth || 8;
  const colorType = opts.colorType == null ? 6 : opts.colorType;
  const interlace = opts.interlace || 0;
  const channels = { 0: 1, 2: 3, 4: 2, 6: 4 }[colorType] || 4;
  const stride = width * channels;
  const raw = Buffer.alloc(height * (stride + 1));
  for (let y = 0; y < height; y++) {
    const row = y * (stride + 1);
    raw[row] = 0;
    for (let x = 0; x < width; x++) {
      const si = (y * width + x) * 4;
      const o = row + 1 + x * channels;
      if (channels === 1) raw[o] = rgba[si] || 0;
      else if (channels === 2) { raw[o] = rgba[si] || 0; raw[o + 1] = rgba[si + 3] || 0; }
      else if (channels === 3) { raw[o] = rgba[si] || 0; raw[o + 1] = rgba[si + 1] || 0; raw[o + 2] = rgba[si + 2] || 0; }
      else { raw[o] = rgba[si] || 0; raw[o + 1] = rgba[si + 1] || 0; raw[o + 2] = rgba[si + 2] || 0; raw[o + 3] = rgba[si + 3] || 0; }
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = bitDepth;
  ihdr[9] = colorType;
  ihdr[10] = 0;
  ihdr[11] = 0;
  ihdr[12] = interlace;
  return Buffer.concat([PNG_SIG, pngChunk('IHDR', ihdr), pngChunk('IDAT', zlib.deflateSync(raw)), pngChunk('IEND', Buffer.alloc(0))]);
}

function paeth(a, b, c) {
  const p = a + b - c;
  const pa = Math.abs(p - a);
  const pb = Math.abs(p - b);
  const pc = Math.abs(p - c);
  if (pa <= pb && pa <= pc) return a;
  if (pb <= pc) return b;
  return c;
}

/** Decode an 8-bit, non-interlaced PNG to RGBA (used for the on-disk sheet report only). */
function decodePng(buf) {
  if (buf.length < 33) throw new Error('too short for a PNG header');
  for (let i = 0; i < PNG_SIG.length; i++) if (buf[i] !== PNG_SIG[i]) throw new Error('bad PNG signature');
  let off = 8;
  let width = 0, height = 0, bitDepth = 0, colorType = 0, interlace = 0;
  const idat = [];
  while (off + 8 <= buf.length) {
    const len = buf.readUInt32BE(off);
    const type = buf.toString('latin1', off + 4, off + 8);
    const data = buf.subarray(off + 8, off + 8 + len);
    if (type === 'IHDR') {
      width = data.readUInt32BE(0);
      height = data.readUInt32BE(4);
      bitDepth = data[8];
      colorType = data[9];
      interlace = data[12];
    } else if (type === 'IDAT') {
      idat.push(Buffer.from(data));
    } else if (type === 'IEND') {
      break;
    }
    off += 12 + len;
  }
  if (bitDepth !== 8) throw new Error(`bit depth ${bitDepth} (only 8 is decoded)`);
  if (interlace) throw new Error('interlaced PNG (Adam7) is not decoded');
  const channels = { 0: 1, 2: 3, 4: 2, 6: 4 }[colorType];
  if (!channels) throw new Error(`unsupported colour type ${colorType}`);
  const raw = zlib.inflateSync(Buffer.concat(idat));
  const stride = width * channels;
  if (raw.length < height * (stride + 1)) throw new Error('truncated IDAT');
  const out = new Uint8ClampedArray(width * height * 4);
  const cur = Buffer.alloc(stride);
  const prev = Buffer.alloc(stride);
  let p = 0;
  for (let y = 0; y < height; y++) {
    const filter = raw[p++];
    const row = raw.subarray(p, p + stride);
    p += stride;
    for (let x = 0; x < stride; x++) {
      const a = x >= channels ? cur[x - channels] : 0;
      const b = prev[x];
      const c = x >= channels ? prev[x - channels] : 0;
      let v = row[x];
      if (filter === 0) { /* none */ }
      else if (filter === 1) v += a;
      else if (filter === 2) v += b;
      else if (filter === 3) v += Math.floor((a + b) / 2);
      else if (filter === 4) v += paeth(a, b, c);
      else throw new Error(`unknown PNG filter ${filter}`);
      cur[x] = v & 255;
    }
    for (let x = 0; x < width; x++) {
      const o = (y * width + x) * 4;
      const i = x * channels;
      let r, g, bl, al;
      if (colorType === 6) { r = cur[i]; g = cur[i + 1]; bl = cur[i + 2]; al = cur[i + 3]; }
      else if (colorType === 2) { r = cur[i]; g = cur[i + 1]; bl = cur[i + 2]; al = 255; }
      else if (colorType === 0) { r = g = bl = cur[i]; al = 255; }
      else { r = g = bl = cur[i]; al = cur[i + 1]; }
      out[o] = r; out[o + 1] = g; out[o + 2] = bl; out[o + 3] = al;
    }
    prev.set(cur);
  }
  return { width, height, colorType, data: out };
}

